/* I NOMI DEL MOTORE PER IL LINKER.
 *
 * Una funzione o una variabile che un modulo offre agli altri ha un nome che
 * il linker vede, e i nomi del libro sono corti (fail, note, gcd): uno
 * potrebbe essere anche il nome di una funzione di una libreria con cui il
 * programma è collegato, e il linker legherebbe in silenzio l'uno all'altra.
 * Qui ogni nome offerto riceve, per il linker, un prefisso; nei sorgenti resta
 * quello del libro.
 *
 * Va incluso dopo la libreria standard e prima di ogni dichiarazione del
 * motore: lo fa engine_foundations.h, che ogni modulo include per primo.
 *
 * Warning: una riga per ogni funzione e variabile dichiarata nell'interfaccia
 * di un modulo, in ordine alfabetico; Math/tools/engine_modules.py check
 * controlla che ci siano tutte e solo quelle. */
